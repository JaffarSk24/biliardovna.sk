/**
 * Задачи по расписанию запускает только планировщик Webglobe (по адресу) или командная строка.
 * Без этой проверки любой посетитель мог открыть /cron/....php и запустить рассылку или
 * подтверждение броней, заняв процесс сайта. Адреса планировщика указаны в панели Webglobe
 * (Hosting, Web, Cron); если хостинг их сменит, в журнале задач появится код 403.
 */
if (PHP_SAPI !== 'cli') {
    $cronSourceIps = ['62.109.128.59', '62.109.150.10', '62.109.128.13'];
    if (!in_array($_SERVER['REMOTE_ADDR'] ?? '', $cronSourceIps, true)) {
        http_response_code(403);
        exit;
    }
}

